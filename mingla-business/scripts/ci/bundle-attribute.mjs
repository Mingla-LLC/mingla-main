#!/usr/bin/env node
/**
 * Boot-payload attribution — what is ACTUALLY inside `__common` (issue #943).
 *
 * The `__common` chunk has been discussed, capped, and raised five times without
 * anyone ever opening it. Every previous conversation about "tightening the boot
 * path" was therefore a wish: no one could say whether the honest floor was
 * 2.3 MB or 900 KB. This tool answers that, repeatably.
 *
 * HOW IT WORKS: an `expo export -p web --source-maps` emits a .map beside each
 * chunk. A source map's `mappings` field records, for every run of generated
 * characters, which original source file produced it. Walking those segments in
 * order and charging each generated span to its source gives byte-accurate
 * attribution — the same technique source-map-explorer uses, without adding a
 * dependency to the repo.
 *
 * Bytes are attributed as RAW generated characters. That is the right unit for
 * "who is responsible", because compression ratios differ per module and would
 * otherwise let a big-but-repetitive module hide behind a small brotli figure.
 * The customer-felt total stays where it belongs, on the gate itself.
 *
 * NOT part of CI. Source maps roughly double export time and artifact size, so
 * this runs on demand when someone is actually doing the trimming.
 *
 * Usage:
 *   cd mingla-business
 *   npx expo export -p web --source-maps --output-dir /tmp/web-maps
 *   node scripts/ci/bundle-attribute.mjs --build /tmp/web-maps [--top 60] [--group]
 *
 *   --group   roll bytes up to package / workspace-area instead of single files
 *   --json    emit machine-readable output for diffing two exports
 */

import { readFileSync, existsSync, readdirSync } from "node:fs";
import { join } from "node:path";

const argv = process.argv.slice(2);
const argOf = (name, fallback) => {
  const i = argv.indexOf(name);
  return i >= 0 && argv[i + 1] ? argv[i + 1] : fallback;
};
const BUILD = argOf("--build", process.env.ORCH_1083_WEB_BUILD ?? "web-build");
const TOP = Number(argOf("--top", "50"));
const GROUP = argv.includes("--group");
const JSON_OUT = argv.includes("--json");

// ── Base64 VLQ ──────────────────────────────────────────────────────────────
const B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
const B64_MAP = new Map([...B64].map((c, i) => [c, i]));

/** Decode one comma-separated VLQ segment into an array of signed ints. */
function decodeVlq(segment) {
  const out = [];
  let value = 0;
  let shift = 0;
  for (const ch of segment) {
    const digit = B64_MAP.get(ch);
    if (digit === undefined) throw new Error(`bad VLQ char ${JSON.stringify(ch)}`);
    value += (digit & 31) << shift;
    if (digit & 32) {
      shift += 5;
      continue;
    }
    const negative = value & 1;
    value >>>= 1;
    out.push(negative ? (value === 0 ? -0x80000000 : -value) : value);
    value = 0;
    shift = 0;
  }
  return out;
}

/**
 * Attribute every generated byte of `code` to a source file, using `map`.
 *
 * Walks the mappings in generated order. Each segment marks the start of a run;
 * the run ends where the next segment starts (or at end-of-line). Generated
 * characters not covered by any mapping — Metro's module wrappers, the runtime
 * preamble — are charged to a synthetic "(unmapped: bundler runtime + wrappers)"
 * bucket rather than silently dropped, so the parts always sum to the whole.
 */
function attribute(code, map) {
  const sources = map.sources ?? [];
  const lines = code.split("\n");
  const totals = new Map();
  const charge = (name, n) => {
    if (n > 0) totals.set(name, (totals.get(name) ?? 0) + n);
  };

  let srcIndex = 0;
  let mappedTotal = 0;

  const mappingLines = (map.mappings ?? "").split(";");
  for (let genLine = 0; genLine < mappingLines.length; genLine++) {
    const raw = mappingLines[genLine];
    if (!raw) continue;
    const lineLen = (lines[genLine] ?? "").length + 1; // +1 for the newline

    let genCol = 0;
    const segs = [];
    for (const segment of raw.split(",")) {
      if (!segment) continue;
      const fields = decodeVlq(segment);
      genCol += fields[0];
      if (fields.length >= 4) srcIndex += fields[1];
      segs.push({ col: genCol, src: fields.length >= 4 ? srcIndex : null });
    }

    for (let i = 0; i < segs.length; i++) {
      const start = segs[i].col;
      const end = i + 1 < segs.length ? segs[i + 1].col : lineLen;
      const span = Math.max(0, end - start);
      if (segs[i].src === null) continue;
      charge(sources[segs[i].src] ?? `(source #${segs[i].src})`, span);
      mappedTotal += span;
    }
  }

  charge("(unmapped: bundler runtime + module wrappers)", code.length - mappedTotal);
  return totals;
}

/** Strip Metro's server-root prefixes so paths read like repo paths. */
function normalize(source) {
  return source
    .replace(/^webpack:\/\/\//, "")
    .replace(/^\/+/, "")
    .replace(/^(\.\.\/)+/, "");
}

/** Collapse a source path to the thing a human would actually decide about. */
function groupOf(source) {
  if (source.startsWith("(unmapped")) return source;
  const s = normalize(source);

  // Third-party: roll up to the installed package.
  const nm = s.lastIndexOf("node_modules/");
  if (nm >= 0) {
    const parts = s.slice(nm + "node_modules/".length).split("/");
    return `node_modules/${parts[0].startsWith("@") ? `${parts[0]}/${parts[1]}` : parts[0]}`;
  }

  const parts = s.split("/");
  // Shared workspace packages: the package is the decision unit.
  if (parts[0] === "packages") return `packages/${parts[1] ?? ""}`;
  // First-party app code: two levels deep is where ownership actually sits
  // (src/components/event vs src/services), which is what a trim pass needs.
  if (parts[0] === "src" || parts[0] === "app") return parts.slice(0, 3).join("/");
  return parts.slice(0, 2).join("/");
}

// ── Locate the chunks ───────────────────────────────────────────────────────
const JS_DIR = join(BUILD, "_expo", "static", "js", "web");
if (!existsSync(JS_DIR)) {
  console.error(`No web export at ${BUILD}. Run:\n  npx expo export -p web --source-maps --output-dir ${BUILD}`);
  process.exit(1);
}

const html = readFileSync(join(BUILD, "index.html"), "utf8");
const eagerRels = [...html.matchAll(/\/_expo\/static\/js\/web\/([^"']+\.js)/g)].map((m) => m[1]);
if (eagerRels.length === 0) {
  console.error("no eager <script> references found in index.html");
  process.exit(1);
}

const maps = readdirSync(JS_DIR).filter((n) => n.endsWith(".map"));
if (maps.length === 0) {
  console.error(
    `No .map files in ${JS_DIR}.\n` +
      `Attribution needs source maps. Re-export with:\n` +
      `  npx expo export -p web --source-maps --output-dir ${BUILD}`,
  );
  process.exit(1);
}

const report = { build: BUILD, chunks: [] };

for (const rel of eagerRels) {
  const codePath = join(JS_DIR, rel);
  const mapPath = `${codePath}.map`;
  if (!existsSync(mapPath)) {
    console.error(`  (skipping ${rel} — no source map)`);
    continue;
  }
  const code = readFileSync(codePath, "utf8");
  const map = JSON.parse(readFileSync(mapPath, "utf8"));
  const totals = attribute(code, map);

  const rolled = new Map();
  for (const [source, bytes] of totals) {
    const key = GROUP ? groupOf(source) : normalize(source);
    rolled.set(key, (rolled.get(key) ?? 0) + bytes);
  }

  const ranked = [...rolled.entries()].sort((a, b) => b[1] - a[1]);
  report.chunks.push({
    chunk: rel,
    totalBytes: code.length,
    entries: ranked.map(([name, bytes]) => ({ name, bytes })),
  });

  if (JSON_OUT) continue;

  const label = rel.includes("__common")
    ? `${rel}  ← THE EAGER SHARED CHUNK (issue #943)`
    : rel;
  console.log(`\n${"═".repeat(88)}`);
  console.log(label);
  console.log(`total ${code.length.toLocaleString("en-US")} B · ${ranked.length} ${GROUP ? "groups" : "sources"}`);
  console.log("═".repeat(88));
  let shown = 0;
  for (const [name, bytes] of ranked.slice(0, TOP)) {
    const pct = ((bytes / code.length) * 100).toFixed(2);
    console.log(`${String(bytes).padStart(10)}  ${pct.padStart(6)}%  ${name}`);
    shown += bytes;
  }
  if (ranked.length > TOP) {
    const rest = code.length - shown;
    console.log(
      `${String(rest).padStart(10)}  ${((rest / code.length) * 100).toFixed(2).padStart(6)}%  ` +
        `… ${ranked.length - TOP} more`,
    );
  }
}

if (JSON_OUT) console.log(JSON.stringify(report, null, 2));
