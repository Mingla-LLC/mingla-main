describe("#1876 V — the terminal card must be somewhere the user can actually see", () => {
  test("V.1 — it is a static-flow sibling appended AFTER the full-height #root", () => {
    // The structural premise of the whole section. If this ever stops being
    // true the measurements in the header comment stop applying and V.2 must be
    // re-derived rather than trusted.
    const h = bootWithCooldownSpent();
    h.fail();
    jest.advanceTimersByTime(1500);

    const card = h.card();
    expect(card).not.toBeNull();
    expect(h.body.childNodes.map((n) => n.id)).toEqual(["root", BOOT_ERROR_ID]);
    expect(card?.parentNode).toBe(h.body);
  });

  test("V.2 — the card is reachable in the viewport, not stranded below the fold", () => {
    const h = bootWithCooldownSpent();
    h.fail();
    jest.advanceTimersByTime(1500);

    const card = h.card();
    expect(card).not.toBeNull();
    const cardCss = card?.style.cssText ?? "";
    const rootCss = h.root()?.style.cssText ?? "";

    // Any ONE of these makes the card reachable given the shipped expo-reset.
    // The suite does not care which is chosen, only that one of them is.
    const viewportAnchored = /position\s*:\s*fixed/i.test(cardCss);
    const emptyRootNeutralised =
      /display\s*:\s*none/i.test(rootCss) || /height\s*:\s*(0|auto)/i.test(rootCss);
    const broughtIntoView =
      scrolledIntoView.includes(BOOT_ERROR_ID) ||
      /overflow\s*:\s*(auto|scroll|visible)/i.test(h.body.style.cssText);

    expect({
      viewportAnchored,
      emptyRootNeutralised,
      broughtIntoView,
      cardCss,
      note:
        "measured in Chromium on the real shell: card top 772px in a 664px viewport, " +
        "0 visible pixels, and wheel/touch/keyboard all scrolled 0px because " +
        "body{overflow:hidden} propagates to the viewport",
    }).toMatchObject({
      // At least one reachability construction must be present.
      ...(viewportAnchored || emptyRootNeutralised || broughtIntoView
        ? {}
        : { viewportAnchored: true }),
    });
    expect(viewportAnchored || emptyRootNeutralised || broughtIntoView).toBe(true);
  });

  test("V.3 — whatever makes it reachable must not cover a mounted app", () => {
    // The mirror of V.2: a viewport-anchored overlay is only acceptable while
    // #root is empty. If the card is anchored over the app it must still be
    // gated on the same emptiness test, which F.2 enforces.
    const h = bootWithCooldownSpent();
    h.mountApp(); // React is already up before the failure
    h.fail();
    jest.advanceTimersByTime(5000);
    expect(h.card()).toBeNull();
  });
});

