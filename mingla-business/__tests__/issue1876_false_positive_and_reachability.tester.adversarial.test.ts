/**
 * Issue #1876 — TESTER ADVERSARIAL suite.
 *
 * The implementor's two suites prove the right NODE is CREATED. This one asks
 * the two questions they cannot: can a human SEE it, and can it ever appear
 * over a working app? Both were answered by driving the EXACT shipped `<head>`
 * bytes in a real Chromium against the real deployed shell, and both answers
 * were bad. This suite encodes those answers so they can never regress.
 *
 * ---------------------------------------------------------------------------
 * SECTION V — THE CARD IS RENDERED BELOW THE FOLD, ON A PAGE THAT CANNOT SCROLL
 * ---------------------------------------------------------------------------
 * The card is appended to `document.body` as a static-flow sibling AFTER
 * `#root`. The deployed shell ships react-native-web's recommended reset in
 * `<style id="expo-reset">`, verbatim:
 *
 *     html, body { height: 100%; }
 *     body       { overflow: hidden; }
 *     #root      { display: flex; height: 100%; flex: 1; }
 *
 * An EMPTY `#root` therefore still occupies the whole viewport, so a static
 * sibling placed after it starts at 100vh + the card's own 15vh top margin —
 * below the fold by construction. And `body { overflow: hidden }` propagates to
 * the viewport (the root element's own overflow is `visible`), so the user
 * cannot scroll down to it.
 *
 * Measured in Chromium against the real shipped shell, cooldown primed and all
 * three entry chunks 404ing — i.e. the exact scenario SC-8 describes:
 *
 *   viewport         card top   card visible px   wheel   touch drag   keyboard
 *   iPhone 13 390x664   772          0             0 px      0 px        0 px
 *   Pixel 5   393x727   844          0             0 px      0 px        0 px
 *   desktop  1280x800   928          0             0 px       n/a        0 px
 *
 * Only a programmatic `window.scrollTo` reached it, and nothing calls that. The
 * viewport screenshot of the "fixed" page is a pure white rectangle — pixel for
 * pixel the bug this issue is titled after. A DOM-presence assertion passes on
 * that page, which is exactly the green-CI-and-broken-product inversion.
 *
 * V.1 pins the structural fact (static sibling after a full-height `#root`).
 * V.2 requires the card to be reachable. It deliberately accepts ANY of the
 * three constructions that actually achieve it rather than mandating one:
 * viewport-anchoring the host, neutralising the empty `#root`, or restoring
 * scroll and bringing the card into view.
 *
 * ---------------------------------------------------------------------------
 * SECTION F — THE 1500 ms GUARD IS A SNAPSHOT, NOT AN INVARIANT
 * ---------------------------------------------------------------------------
 * `#root`-empty is tested exactly once, when the timer fires, and the card is
 * never removed. Measured boundary, same Chromium harness, mount time relative
 * to the suppression event:
 *
 *   mount at 1400 ms -> no card      mount at 1501 ms -> card, and it STAYS
 *   mount at 1490 ms -> no card      mount at 1600 ms -> card, and it STAYS
 *   mount at 1499 ms -> no card      mount at 2500 ms -> card, and it STAYS
 *                                    mount at 5000 ms -> card, and it STAYS
 *
 * The boundary is exact and correct at 1500 ms. What is wrong is what happens
 * on the far side of it: a slow-but-successful boot that commits at 1501 ms
 * gets a permanent "this page didn't finish loading" card sitting over a
 * perfectly healthy app, with no path back. Today that defect is masked by
 * Section V — the false-positive card is below the fold too — so fixing V
 * without fixing F turns an invisible false positive into a visible one.
 *
 * F.2 is the contract: once the app mounts, the card must go.
 *
 * ---------------------------------------------------------------------------
 * SECTION D — THE INVERSE REGRESSION: DEEP LINKS MUST NEVER 404
 * ---------------------------------------------------------------------------
 * Over-excluding is worse than under-excluding: a route that stops reaching the
 * shell is a dead public link. #1485's A.6 guards this, but only against the
 * `_expo/static/` alternate by name, so it did not widen when `assets/` joined.
 * D.1 is generic over EVERY alternate in the shipped alternation, derived from
 * the real `app/` tree, so a fourth alternate is covered the day it lands.
 *
 * ---------------------------------------------------------------------------
 * SECTION E — RESIDUAL PATH SHAPES, PINNED SO THEY STAY VISIBLE
 * ---------------------------------------------------------------------------
 * Probed live on production 2026-08-11: `/Assets/…`, `/%61ssets/…` and the
 * bare `/assets` tree root all still resolve to the shell. None is generated by
 * a browser or by this app, so none is a defect to fix here — but they are
 * holes in "the build-output tree never answers with HTML", and pinning them is
 * how they stay visible rather than being rediscovered a third time.
 *
 * Fails-on-revert: V.2 and F.2 fail against `fe76b973a` (the state that shipped
 * this issue's fix) and pass only once the card is reachable and self-clearing.
 * D.1 fails the moment an alternate shadows a real route; E fails on drift.
 */

