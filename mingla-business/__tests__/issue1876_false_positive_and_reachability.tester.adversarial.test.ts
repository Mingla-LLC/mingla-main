/** Every alternate inside the shipped `(?!…)` lookahead, in order. */
const ALTERNATES = (/\(\?!([^)]+)\)/.exec(catchAll.source)?.[1] ?? "").split("|");

function walkRoutes(dir: string, rel = ""): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith(".")) continue;
    const childRel = rel === "" ? entry.name : `${rel}/${entry.name}`;
    if (entry.isDirectory()) out.push(...walkRoutes(path.join(dir, entry.name), childRel));
    else if (/\.tsx?$/.test(entry.name) && !entry.name.startsWith("+")) out.push(childRel);
  }
  return out;
}

describe("#1876 D — over-excluding would 404 live deep links, so prove it cannot", () => {
  test("D.1 — no alternate shadows any real route, generically over the whole list", () => {
    // #1485's A.6 hard-codes `_expo/static/`, so it did not widen when
    // `assets/` joined and will not widen for the next one either. This is
    // derived from the alternation itself.
    expect(ALTERNATES.length).toBeGreaterThanOrEqual(3);
    const routeFiles = walkRoutes(APP_DIR);
    expect(routeFiles.length).toBeGreaterThan(30); // guard against a walker no-op

    const firstSegments = new Set(
      routeFiles
        .map((file) => file.split("/")[0].replace(/\.tsx?$/, ""))
        .filter((segment) => !segment.startsWith("(") && !segment.startsWith("_")),
    );

    const collisions: string[] = [];
    for (const alternate of ALTERNATES) {
      const prefix = alternate.replace(/\$$/, "").replace(/\/$/, "");
      for (const segment of firstSegments) {
        if (segment === prefix) collisions.push(`${alternate} shadows app/${segment}`);
      }
    }
    expect(collisions).toEqual([]);
  });

  test("D.2 — every top-level route segment still reaches the SPA shell", () => {
    const routeFiles = walkRoutes(APP_DIR);
    const segments = [
      ...new Set(
        routeFiles
          .map((file) => file.split("/")[0].replace(/\.tsx?$/, ""))
          .filter((segment) => !segment.startsWith("(")),
      ),
    ].sort();

    const notCaught = segments.filter((segment) => !COMPILED_CATCH_ALL.test(`/${segment}`));
    expect(notCaught).toEqual([]);
  });

  test("D.3 — the alternates that exist correspond to build output, not to routes", () => {
    expect(ALTERNATES).toContain("_expo/static/");
    expect(ALTERNATES).toContain("assets/");
    // Anything ending in `/` is a directory prefix; anything else must be an
    // exact-match `$` form, which cannot swallow a subtree by accident.
    for (const alternate of ALTERNATES) {
      expect([alternate, alternate.endsWith("/") || alternate.endsWith("$")]).toEqual([
        alternate,
        true,
      ]);
    }
  });
});

