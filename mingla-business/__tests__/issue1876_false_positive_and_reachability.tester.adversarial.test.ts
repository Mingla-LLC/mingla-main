describe("#1876 F — the card must never end up sitting over a working app", () => {
  test("F.1 — the emptiness test is taken at 1500 ms, and 1499 ms is still safe", () => {
    const h = bootWithCooldownSpent();
    h.fail();
    jest.advanceTimersByTime(1499);
    expect(h.card()).toBeNull(); // nothing has fired yet
    h.mountApp(); // a slow-but-successful boot commits with 1 ms to spare
    jest.advanceTimersByTime(1);
    expect(h.card()).toBeNull();
    jest.advanceTimersByTime(10_000);
    expect(h.card()).toBeNull();
  });

  test("F.2 — a boot that commits AFTER the guard fires must clear the card", () => {
    // Chromium-measured: at 1501 ms the card appears and never leaves. On a
    // slow phone the entry bundle can commit seconds after a suppressed lazy
    // chunk error, and the user is then told the page did not load while
    // looking at a page that did. The emptiness test has to be an invariant
    // that holds for as long as the card is on screen, not a single sample.
    const h = bootWithCooldownSpent();
    h.fail();
    jest.advanceTimersByTime(1501);
    expect(h.card()).not.toBeNull(); // the guard fired while #root was empty

    h.mountApp(); // React commits 1 ms late
    jest.advanceTimersByTime(5000);

    expect(h.card()).toBeNull();
  });

  test("F.3 — clearing the card must not disturb the app that displaced it", () => {
    const h = bootWithCooldownSpent();
    h.fail();
    jest.advanceTimersByTime(1501);
    h.mountApp();
    jest.advanceTimersByTime(5000);

    const root = h.root();
    expect(root).not.toBeNull();
    expect(root?.childNodes.map((n) => n.id)).toEqual(["app-shell"]);
    expect(h.reload).not.toHaveBeenCalled(); // no reload-loop was introduced
  });

  test("F.4 — the arm latch must not be spent by a failure the app survived", () => {
    // A suppressed LAZY-route failure while React is alive correctly renders no
    // card. It must not also burn the one-shot latch, or a genuine entry-bundle
    // blank page later in the same document gets nothing at all.
    const h = bootWithCooldownSpent();
    h.mountApp();
    h.fail(); // lazy chunk dies, app survives
    jest.advanceTimersByTime(5000);
    expect(h.card()).toBeNull();

    // The app is torn back down to an empty #root and fails again.
    const root = h.root();
    while (root !== null && root.childNodes.length > 0) root.removeChild(root.childNodes[0]);
    h.fail();
    jest.advanceTimersByTime(5000);
    expect(h.card()).not.toBeNull();
  });
});

