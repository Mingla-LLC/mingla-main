// ---------------------------------------------------------------------------
// Independent synthetic DOM. Written from scratch rather than reused, and
// deliberately RICHER than the implementor's: nodes can be removed, and a
// MutationObserver exists, so any of the plausible fixes for F.2 can be
// expressed and observed instead of being assumed away by a harness that
// cannot represent them.
// ---------------------------------------------------------------------------

type Node = {
  tagName: string;
  id: string;
  type: string;
  textContent: string;
  style: { cssText: string };
  attributes: Record<string, string>;
  childNodes: Node[];
  parentNode: Node | null;
  onclick: null | (() => void);
  setAttribute: (name: string, value: string) => void;
  appendChild: (child: Node) => Node;
  removeChild: (child: Node) => Node;
  remove: () => void;
  scrollIntoView: () => void;
};

const observers: { target: Node; cb: () => void }[] = [];

function notify(node: Node | null): void {
  for (let cursor = node; cursor !== null; cursor = cursor.parentNode) {
    for (const entry of observers) if (entry.target === cursor) entry.cb();
  }
}

function makeNode(tagName: string): Node {
  const node: Node = {
    tagName,
    id: "",
    type: "",
    textContent: "",
    style: { cssText: "" },
    attributes: {},
    childNodes: [],
    parentNode: null,
    onclick: null,
    setAttribute: (name, value) => {
      node.attributes[name] = value;
    },
    appendChild: (child) => {
      child.parentNode = node;
      node.childNodes.push(child);
      notify(node);
      return child;
    },
    removeChild: (child) => {
      const at = node.childNodes.indexOf(child);
      if (at >= 0) node.childNodes.splice(at, 1);
      child.parentNode = null;
      notify(node);
      return child;
    },
    remove: () => {
      if (node.parentNode !== null) node.parentNode.removeChild(node);
    },
    scrollIntoView: () => {
      scrolledIntoView.push(node.id);
    },
  };
  return node;
}

let scrolledIntoView: string[] = [];

function findById(node: Node, id: string): Node | null {
  if (node.id === id) return node;
  for (const child of node.childNodes) {
    const hit = findById(child, id);
    if (hit !== null) return hit;
  }
  return null;
}

/** The EXACT `<script>` bytes the build injects — evaluated, never grepped. */
function shippedScriptBody(): string {
  const literal = injectSource.match(/const CHUNK_RECOVERY_SCRIPT =\s*(`[^`]*`);/);
  if (literal === null) throw new Error("CHUNK_RECOVERY_SCRIPT template literal not found");
  const named = (name: string): string => {
    const hit = injectSource.match(new RegExp(`const ${name} = "([^"]*)";`));
    if (hit === null) throw new Error(`missing const ${name}`);
    return hit[1];
  };
  const cooldown = injectSource.match(/const CHUNK_RECOVERY_COOLDOWN_MS = ([0-9_]+);/);
  if (cooldown === null) throw new Error("missing const CHUNK_RECOVERY_COOLDOWN_MS");
  const build = new Function(
    "CHUNK_RECOVERY_MARKER",
    "CHUNK_RECOVERY_KEY",
    "CHUNK_RECOVERY_COOLDOWN_MS",
    `return ${literal[1]};`,
  ) as (marker: string, key: string, cooldown: number) => string;
  return build(named("CHUNK_RECOVERY_MARKER"), named("CHUNK_RECOVERY_KEY"), Number(cooldown[1]))
    .replace(/^<script[^>]*>/, "")
    .replace(/<\/script>$/, "");
}

const SCRIPT_BODY = shippedScriptBody();

const realWindow = (global as unknown as { window?: unknown }).window;

