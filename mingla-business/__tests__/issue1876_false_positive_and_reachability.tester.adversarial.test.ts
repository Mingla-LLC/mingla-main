type Harness = {
  body: Node;
  root: () => Node | null;
  card: () => Node | null;
  reload: jest.Mock;
  /** Fire a genuine capture-phase resource error for a chunk URL. */
  fail: (src?: string) => void;
  /** React commits its first render into `#root`. */
  mountApp: () => void;
};

/** Boots the shipped bytes with the cooldown ALREADY spent, i.e. suppression. */
function bootWithCooldownSpent(): Harness {
  const listeners = new Map<string, ((event: unknown) => void)[]>();
  const store = new Map<string, string>([[SHARED_KEY, String(Date.now())]]);
  const reload = jest.fn();

  const body = makeNode("body");
  const rootNode = Object.assign(makeNode("div"), { id: "root" });
  body.appendChild(rootNode);

  const doc = {
    body,
    createElement: (tag: string) => makeNode(tag),
    getElementById: (id: string) => findById(body, id),
    addEventListener: () => undefined,
    querySelector: (sel: string) => findById(body, sel.replace(/^#/, "")),
  };

  const fakeWindow: Record<string, unknown> = {
    addEventListener: (type: string, listener: (event: unknown) => void): void => {
      const existing = listeners.get(type) ?? [];
      existing.push(listener);
      listeners.set(type, existing);
    },
    document: doc,
    location: { reload, replace: jest.fn(), assign: jest.fn(), href: "https://host.usemingla.com/checkout/abc" },
    sessionStorage: {
      getItem: (key: string): string | null => store.get(key) ?? null,
      setItem: (key: string, value: string): void => void store.set(key, value),
      removeItem: (key: string): void => void store.delete(key),
    },
    setTimeout: ((handler: () => void, delay?: number) => setTimeout(handler, delay)) as typeof setTimeout,
    setInterval: ((handler: () => void, delay?: number) => setInterval(handler, delay)) as typeof setInterval,
    clearInterval: ((handle: never) => clearInterval(handle)) as typeof clearInterval,
    clearTimeout: ((handle: never) => clearTimeout(handle)) as typeof clearTimeout,
    requestAnimationFrame: ((handler: () => void) => setTimeout(handler, 16)) as unknown,
    MutationObserver: class {
      private readonly cb: () => void;
      constructor(cb: () => void) {
        this.cb = cb;
      }
      observe(target: Node): void {
        observers.push({ target, cb: this.cb });
      }
      disconnect(): void {
        for (let i = observers.length - 1; i >= 0; i -= 1) {
          if (observers[i].cb === this.cb) observers.splice(i, 1);
        }
      }
      takeRecords(): unknown[] {
        return [];
      }
    },
  };

  (global as unknown as { window?: unknown }).window = fakeWindow;
  const quietConsole = { warn: jest.fn(), error: jest.fn(), log: jest.fn() };
  new Function("window", "console", SCRIPT_BODY)(fakeWindow, quietConsole);

  return {
    body,
    root: () => findById(body, "root"),
    card: () => findById(body, BOOT_ERROR_ID),
    reload,
    fail: (src = CHUNK_URL) => {
      const registered = listeners.get("error") ?? [];
      expect(registered.length).toBeGreaterThan(0);
      for (const listener of registered) listener({ target: { src } });
    },
    mountApp: () => {
      const root = findById(body, "root");
      if (root === null) throw new Error("#root vanished");
      root.appendChild(Object.assign(makeNode("div"), { id: "app-shell" }));
    },
  };
}

