describe("#1876 E — path shapes the exclusion does NOT cover (pinned, not fixed)", () => {
  test("E.1 — case and percent-encoded variants still reach the shell", () => {
    // Probed live 2026-08-11: all three returned `200 text/html` on production
    // before this change, and the literal alternation does not address them.
    // No browser and nothing in this app emits them, so they are documented
    // rather than fixed — but they are holes in "the build-output tree never
    // answers with HTML" and must not be rediscovered a third time.
    for (const url of [
      "/Assets/does-not-exist-0000.png",
      "/ASSETS/does-not-exist-0000.png",
      "/%61ssets/does-not-exist-0000.png",
      "/assets%2Fdoes-not-exist-0000.png",
    ]) {
      expect([url, COMPILED_CATCH_ALL.test(url)]).toEqual([url, true]);
    }
  });

  test("E.2 — the bare tree root `/assets` is not covered by the `assets/` prefix", () => {
    expect(COMPILED_CATCH_ALL.test("/assets")).toBe(true);
    expect(COMPILED_CATCH_ALL.test("/assets/")).toBe(false);
  });

  test("E.3 — a nested `assets/` segment is correctly NOT excluded", () => {
    // The inverse guard: these are real SPA routes and must keep resolving.
    for (const url of ["/x/assets/y.png", "/venue/assets/create", "/b/assets/v/rooftop"]) {
      expect([url, COMPILED_CATCH_ALL.test(url)]).toEqual([url, true]);
    }
  });

  test("E.4 — the two bundle-referenced assets that are ABSENT from the deploy will now 404", () => {
    // Live probe 2026-08-11: both are referenced by the shipped entry bundle
    // and both returned `200 text/html` — they are not in the export at all.
    // After this change they become honest 404s. Recorded so the new 404s in
    // production logs are expected, not a fresh incident.
    for (const url of ["/assets/images/favicon.png", "/assets/images/icon.png"]) {
      expect([url, COMPILED_CATCH_ALL.test(url)]).toEqual([url, false]);
    }
  });
});
