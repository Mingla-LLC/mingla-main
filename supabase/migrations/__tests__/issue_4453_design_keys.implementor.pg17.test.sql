\set ON_ERROR_STOP on
-- #4453 PR 4: executable PostgreSQL 17 proof that the website design keys are one list.
-- MINGLA-INVARIANT: I-SITES-DESIGN-KEYS-ONE-LIST | issue #4453 | brand_site_design_keys() equals site-contracts DESIGN_KEYS (generated fixture); the plan CHECK, brand_site_plan_save_design and brand_context_completeness_internal read it and hold no literal key list.
--
-- T-1 SC-D1   brand_site_design_keys() returns exactly the generated DESIGN_KEYS, in order.
-- T-2         it is IMMUTABLE, SQL, and callable by anon, authenticated and service_role.
-- T-3 SC-D1   brand_site_plans_design_key_check reads the function (no literal list).
-- T-4         a key outside the list is refused by the CHECK (23514); a listed key and NULL pass.
-- T-5         brand_site_plan_save_design and brand_context_completeness_internal call the function
--             and carry no literal 'atelier'/'voyage' list.
--
-- FAILS-ON-REVERT: drop 20280722004453 -> T-1 (function missing); a literal list in either
-- function -> T-5; the old CHECK -> T-3; a key added to DESIGN_KEYS without replacing the
-- function -> T-1 (the fixture is regenerated by scripts/sites/sync-site-contracts.mjs).

\ir issue_4453_design_keys.fixture.sql

BEGIN;

CREATE OR REPLACE FUNCTION pg_temp.k_assert(p_ok boolean, p_label text)
RETURNS void LANGUAGE plpgsql AS $a$
BEGIN
  IF NOT COALESCE(p_ok, false) THEN RAISE EXCEPTION 'issue #4453 design keys FAIL: %', p_label; END IF;
  RAISE NOTICE 'PASS  %', p_label;
END
$a$;

SELECT pg_temp.k_assert(public.brand_site_design_keys() = :'contract_design_keys'::text[],
  'T-1 brand_site_design_keys() = generated DESIGN_KEYS ' || :'contract_design_keys');

SELECT pg_temp.k_assert(
  (SELECT p.provolatile = 'i' AND l.lanname = 'sql' AND p.prorettype = 'text[]'::regtype
     FROM pg_proc p JOIN pg_language l ON l.oid = p.prolang
    WHERE p.oid = 'public.brand_site_design_keys()'::regprocedure),
  'T-2a immutable SQL returning text[]');
SELECT pg_temp.k_assert(
  has_function_privilege('anon', 'public.brand_site_design_keys()', 'EXECUTE')
  AND has_function_privilege('authenticated', 'public.brand_site_design_keys()', 'EXECUTE')
  AND has_function_privilege('service_role', 'public.brand_site_design_keys()', 'EXECUTE'),
  'T-2b anon, authenticated and service_role may call it');

SELECT pg_temp.k_assert(
  (SELECT pg_get_constraintdef(c.oid) LIKE '%brand_site_design_keys()%'
          AND pg_get_constraintdef(c.oid) NOT LIKE '%''atelier''%'
     FROM pg_constraint c
    WHERE c.conrelid = 'public.brand_site_plans'::regclass
      AND c.conname = 'brand_site_plans_design_key_check'),
  'T-3 the plan CHECK reads brand_site_design_keys()');

-- T-4: the real constraint expression, evaluated for listed, unlisted and NULL keys.
CREATE TEMP TABLE k_probe (design_key text);
DO $t4$
DECLARE
  v_def text;
BEGIN
  SELECT pg_get_constraintdef(c.oid) INTO v_def
    FROM pg_constraint c
   WHERE c.conrelid = 'public.brand_site_plans'::regclass AND c.conname = 'brand_site_plans_design_key_check';
  EXECUTE format('ALTER TABLE k_probe ADD CONSTRAINT k_probe_check %s', v_def);
END
$t4$;
INSERT INTO k_probe VALUES ('voyage'), ('atelier'), (NULL);
SELECT pg_temp.k_assert(true, 'T-4a voyage, atelier and NULL pass the CHECK');
DO $t4b$
BEGIN
  BEGIN
    INSERT INTO k_probe VALUES ('nocturne');
    RAISE EXCEPTION 'issue #4453 design keys FAIL: T-4b an unlisted key was accepted';
  EXCEPTION WHEN check_violation THEN
    RAISE NOTICE 'PASS  T-4b an unlisted key is refused (23514)';
  END;
END
$t4b$;

SELECT pg_temp.k_assert(
  (SELECT bool_and(p.prosrc LIKE '%brand_site_design_keys()%' AND p.prosrc NOT LIKE '%''atelier''%' AND p.prosrc NOT LIKE '%''voyage''%')
     FROM pg_proc p
    WHERE p.oid IN ('public.brand_site_plan_save_design(uuid,integer,text,text,text)'::regprocedure,
                    'public.brand_context_completeness_internal(uuid)'::regprocedure)),
  'T-5 save_design and completeness_internal read the function, no literal list');

ROLLBACK;
