create temp view w5_fn as
select p.oid, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' as sig, p.proname, p.prosecdef, l.lanname, p.proconfig,
       exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e') as in_extension
  from pg_proc p join pg_language l on l.oid = p.prolang
 where p.pronamespace = 'public'::regnamespace;

-- GRANTS
select pg_temp.chk('GRANTS', 'every revoked signature exists',
  (select coalesce(string_agg(r.sig, ', '), 'none') from w5_revoked r where not exists (select 1 from w5_fn f where f.sig = r.sig)), 'none');
select pg_temp.chk('GRANTS', 'anon cannot execute any revoked function',
  (select coalesce(string_agg(f.sig, ', '), 'none') from w5_fn f join w5_revoked r using (sig) where has_function_privilege('anon', f.oid, 'EXECUTE')), 'none');
select pg_temp.chk('GRANTS', 'authenticated cannot execute any revoked function',
  (select coalesce(string_agg(f.sig, ', '), 'none') from w5_fn f join w5_revoked r using (sig) where has_function_privilege('authenticated', f.oid, 'EXECUTE')), 'none');
select pg_temp.chk('GRANTS', 'service_role still executes every revoked function',
  (select coalesce(string_agg(f.sig, ', '), 'none') from w5_fn f join w5_revoked r using (sig) where not has_function_privilege('service_role', f.oid, 'EXECUTE')), 'none');

-- KEEP
select pg_temp.chk('KEEP', 'every intended-public signature that exists is anon-executable',
  (select coalesce(string_agg(f.sig, ', '), 'none') from w5_fn f join w5_intended_public i using (sig) where not has_function_privilege('anon', f.oid, 'EXECUTE')), 'none');
select pg_temp.chk('KEEP', 'no function production served over REST lost anon or authenticated EXECUTE',
  (select coalesce(string_agg(c.proname, ', ' order by c.proname), 'none') from w5_called c
     left join lateral (select bool_or(has_function_privilege('anon', f.oid, 'EXECUTE')) a, bool_or(has_function_privilege('authenticated', f.oid, 'EXECUTE')) b
                          from w5_fn f where f.proname = c.proname) cur on true
    where (c.anon_x and not coalesce(cur.a, false)) or (c.auth_x and not coalesce(cur.b, false))), 'none');
select pg_temp.chk('KEEP', 'the revoke list and the production REST callers do not overlap',
  (select coalesce(string_agg(distinct f.proname, ', '), 'none') from w5_fn f join w5_revoked r using (sig) join w5_called c on c.proname = f.proname), 'none');

