    where to_regclass('public.' || v.view_name) is not null and has_table_privilege(r.rolname, ('public.' || v.view_name)::regclass, pr.p)), 'none');

-- SMOKE (each call in its own sub-transaction; only a permission error counts)
do $t$
declare r record; v_sql text; v_bad text[] := '{}'; v_calls integer := 0; v_stmts text[]; v_labels text[]; i integer;
begin
  set local statement_timeout = '10s';
  -- build every statement as the suite owner, then run them as anon
  select array_agg(format('select public.%I(%s)', f.proname,
           (select coalesce(string_agg('null::' || format_type(t, null), ', ' order by ord), '')
              from unnest(p.proargtypes::oid[]) with ordinality a(t, ord))) order by f.sig),
         array_agg(f.sig order by f.sig)
    into v_stmts, v_labels
    from w5_fn f join pg_proc p on p.oid = f.oid
   where f.proname = any (array['pg_public_event_by_slug', 'pg_public_rsvp_by_slug', 'pg_public_experience_by_slug', 'pg_public_brand_upcoming', 'pg_public_event_display_prices', 'pg_public_event_tier_pricing', 'pg_public_ticket_types_remaining', 'pg_direct_event_checkout_bundle', 'pg_public_trips_by_brand', 'pg_public_experiences_by_brand', 'pg_public_menu_item_sales', 'pg_public_stay_details', 'issue_1384_supported_currencies', 'brand_enquiry_public_profile', 'pg_brand_can_collect', 'pg_brands_can_collect']);
  select v_stmts || array_agg(format('select 1 from public.%I limit 1', view_name) order by view_name),
         v_labels || array_agg('view ' || view_name order by view_name)
    into v_stmts, v_labels
    from w5_owner_views where to_regclass('public.' || view_name) is not null and view_name not like 'ad_public_site%';
  perform set_config('request.jwt.claim.sub', '', true);
  perform set_config('request.jwt.claim.role', 'anon', true);
  set local role anon;
  for i in 1 .. coalesce(cardinality(v_stmts), 0) loop
    begin
      execute v_stmts[i];
    exception when insufficient_privilege or undefined_function then v_bad := v_bad || (v_labels[i] || ' ' || sqlstate);
              when others then null; -- a validation error for null input is fine
    end;
    v_calls := v_calls + 1;
  end loop;
  reset role;
  perform pg_temp.chk('SMOKE', format('anon: %s buyer RPC overloads and public views answer without a permission error', v_calls),
    coalesce(nullif(array_to_string(v_bad, ', '), ''), 'none'), 'none');
  perform pg_temp.chk('SMOKE', 'anon smoke covered the buyer RPCs', (v_calls >= 16)::text, 'true');
end;
$t$;

