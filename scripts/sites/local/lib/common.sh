# The Core stack is the repository's own Supabase project, started from a
# generated copy of supabase/config.toml: the copy carries a distinct project
# id (so container names never collide with another chat's stack), loopback
# ports in the 5532x range, and only the services Sites needs. Functions are a
# symlink to the real directory.
#
# Migrations are NOT handed to the Supabase CLI: the repository holds several
# files that share a version prefix (e.g. two 20260612000000_*), which the
# CLI's version-keyed ledger rejects with a duplicate key. The stack starts
# with an empty migrations directory and replay_core_migrations applies every
# file in filename order with psql — the same canonical replay CI uses.
write_core_stack_config() {
  mkdir -p "${CORE_WORKDIR}/supabase"
  if [[ -L "${CORE_WORKDIR}/supabase/migrations" ]]; then
    rm "${CORE_WORKDIR}/supabase/migrations"
  fi
  mkdir -p "${CORE_WORKDIR}/supabase/migrations"
  ln -sfn "${repo_root}/supabase/functions" "${CORE_WORKDIR}/supabase/functions"
  # Some functions import shared code from the repo's packages/ by relative
  # path (../../packages/...), which resolves against this workdir.
  ln -sfn "${repo_root}/packages" "${CORE_WORKDIR}/packages"
  local functions_toml
  functions_toml="$(mktemp "${TMPDIR:-/tmp}/sites-local-functions.XXXXXX")"
  node "${repo_root}/.github/scripts/ci-discovery/function-policy.mjs" \
    --write-config "$functions_toml" >/dev/null
  {
    cat <<TOML
# GENERATED by scripts/sites/local/start-local-sites.sh — do not edit.
project_id = "${SITES_LOCAL_CORE_PROJECT_ID}"

[api]
enabled = true
port = ${SITES_LOCAL_CORE_API_PORT}
schemas = ["public", "graphql_public"]
extra_search_path = ["public", "extensions"]
max_rows = 1000

[db]
port = ${SITES_LOCAL_CORE_DB_PORT}
shadow_port = ${SITES_LOCAL_CORE_SHADOW_PORT}
major_version = 17

[db.pooler]
enabled = false
port = 55329

[db.seed]
enabled = false

[realtime]
enabled = false

[studio]
enabled = false
port = 55323

[inbucket]
enabled = false
port = 55324

[storage]
enabled = true

[auth]
enabled = true
site_url = "http://localhost:${SITES_LOCAL_STUDIO_PORT}"
additional_redirect_urls = []
enable_signup = false

# Email sign-in stays ON (the seed users and the runtime storage reader sign in
# with a password); setting [auth.email] enable_signup = false would switch
# the whole email provider off. Sign-ups are closed by [auth] enable_signup.
[auth.email]
enable_confirmations = false

[edge_runtime]
enabled = true
policy = "per_worker"
inspector_port = ${SITES_LOCAL_CORE_INSPECTOR_PORT}

[analytics]
enabled = false
port = 55327
TOML
    grep -v '^project_id' "$functions_toml"
  } > "${CORE_WORKDIR}/supabase/config.toml"
  rm -f "$functions_toml"
}

# Apply every repository migration not yet applied to the local Core database,
# in filename order, recording each in a local-only ledger
# (sites_local.applied_migrations). Re-runs apply only new files.
replay_core_migrations() {
  local db_url="$1"
  case "$db_url" in
    postgresql://*@127.0.0.1:*|postgresql://*@localhost:*) ;;
    *) echo "FAIL sites-local: refusing to replay migrations into a non-loopback database" >&2; return 2 ;;
  esac
  psql "$db_url" -X -q -v ON_ERROR_STOP=1 -c \
    "CREATE SCHEMA IF NOT EXISTS sites_local; CREATE TABLE IF NOT EXISTS sites_local.applied_migrations (name text PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now()); REVOKE ALL ON SCHEMA sites_local FROM PUBLIC;" >/dev/null
  local applied count=0 file name
  applied="$(psql "$db_url" -X -q -At -c "SELECT name FROM sites_local.applied_migrations")"
  while IFS= read -r file; do
    name="$(basename "$file")"
    if grep -qxF "$name" <<<"$applied"; then continue; fi
    if ! psql "$db_url" -X -q -v ON_ERROR_STOP=1 -f "$file" >/dev/null 2>"${STATE_DIR}/migration.err"; then
      echo "FAIL sites-local: migration ${name} failed:" >&2
      tail -5 "${STATE_DIR}/migration.err" >&2
      return 1
    fi
    printf '%s\n' "INSERT INTO sites_local.applied_migrations(name) VALUES (:'name');" |
      psql "$db_url" -X -q -v ON_ERROR_STOP=1 -v name="$name" >/dev/null
    count=$((count + 1))
  done < <(find "${repo_root}/supabase/migrations" -maxdepth 1 -type f -name '*.sql' | sort)
  log "applied ${count} Core migration(s)"
}

# #2829 W8 — `run-local-sites.sh --frozen`: serve the Core edge functions from
# a snapshot of the CURRENT COMMIT instead of the live tree. `supabase
# functions serve` watches its functions folder and restarts the edge runtime
# on any change; on the live symlinked tree, ordinary code edits restarted a
# long-lived preview under its viewer (incident 2026-10-26, see the runbook).
# The snapshot is `git archive HEAD supabase/functions packages` (the same
# layout as the core workdir: functions plus the shared packages they import),
# with the generated stack config copied in so it attaches to the same stack.
# Uncommitted edits are NOT in it, by design. Prints the snapshot workdir.
prepare_frozen_functions_workdir() {
  local sha frozen tmp
  sha="$(git -C "$repo_root" rev-parse --short=12 HEAD)" || return 2
  [[ "$sha" =~ ^[0-9a-f]{12}$ ]] || { echo "FAIL sites-local: cannot read HEAD" >&2; return 2; }
  [[ -f "${CORE_WORKDIR}/supabase/config.toml" ]] || {
    echo "FAIL sites-local: ${CORE_WORKDIR}/supabase/config.toml missing; run start-local-sites.sh first" >&2; return 2; }
  frozen="${SITES_LOCAL_STACKS_DIR}/frozen-${sha}"
  if [[ ! -f "${frozen}/.complete" ]]; then
    rm -rf "$frozen"
    mkdir -p "$SITES_LOCAL_STACKS_DIR" || return 2
    tmp="$(mktemp -d "${SITES_LOCAL_STACKS_DIR}/frozen-tmp.XXXXXX")"
    git -C "$repo_root" archive --format=tar HEAD supabase/functions packages | tar -x -C "$tmp" || {
      rm -rf "$tmp"; echo "FAIL sites-local: git archive failed" >&2; return 2; }
    # The local functions env (keys) is gitignored, so it is never archived;
    # functions serve reads it from --env-file.
    mv "$tmp" "$frozen"
    printf '%s\n' "$sha" > "${frozen}/.complete"
  fi
  cp "${CORE_WORKDIR}/supabase/config.toml" "${frozen}/supabase/config.toml"
  if ! git -C "$repo_root" diff --quiet HEAD -- supabase/functions packages; then
    echo "NOTE sites-local: uncommitted edits under supabase/functions or packages are NOT served (--frozen serves ${sha})" >&2
  fi
  printf '%s\n' "$frozen"
}

# #2829 W9a (A16) — keep `host.docker.internal` resolvable inside the Core
# edge-runtime container. After a colima VM restart (or when `functions
# serve` recreates the container) the name has no entry there, and every
# Core → Studio / runtime call times out (runbook: Traps). This watcher adds
# the VM's host address once per container start, as root inside THAT
# container only; it never touches the Mac's network or another container.
# Prints one line per entry it adds. Runs until killed.
edge_host_gateway_watch() {
  local container="supabase_edge_runtime_${SITES_LOCAL_CORE_PROJECT_ID}" profile="${SITES_LOCAL_COLIMA_PROFILE:-mingla-2829}" ip
  while true; do
    if docker inspect -f '{{.State.Running}}' "$container" 2>/dev/null | grep -qx true &&
      ! docker exec "$container" getent hosts host.docker.internal >/dev/null 2>&1; then
      ip="$(edge_host_gateway_address "$profile")"
      if [[ "$ip" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]] &&
        docker exec -u root "$container" sh -c "printf '%s host.docker.internal\n' '$ip' >> /etc/hosts" 2>/dev/null; then
        log "edge runtime: added host.docker.internal -> ${ip} (container ${container})"
      else
        log "WARN edge runtime: host.docker.internal is missing and could not be added; see the runbook Traps"
      fi
    fi
    sleep 5
  done
}

# The Docker VM's address for the Mac: colima's host.lima.internal, else the
# lima default.
edge_host_gateway_address() {
  local profile="$1" found=""
  if command -v colima >/dev/null 2>&1; then
    found="$(colima ssh -p "$profile" -- getent hosts host.lima.internal 2>/dev/null | awk '{print $1; exit}')"
  fi
  printf '%s\n' "${found:-192.168.5.2}"
}
