#!/usr/bin/env node
// #2829 — point Mingla Business web (Expo) at the LOCAL Sites stack.
//
//   node scripts/sites/local/business-web.mjs env --port 8190
//     writes scripts/sites/local/.state/business-web.env (gitignored, 0600)
//     from the running Core stack's status file. run-business-web.sh sources it.
//   node scripts/sites/local/business-web.mjs code <role|email>
//     prints a fresh 6-digit sign-in code for a LOCAL seeded user. The Business
//     app signs in by emailed code and the local stack sends no email, so ask
//     for a code in the app first, then run this and type the code it prints.
//
// Loopback only: every URL is checked with assertLoopbackUrl, and nothing here
// can reach a hosted project. Keys are written to the gitignored env file and
// never printed.
import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  assertLoopbackUrl,
  parseEnvFile,
  PORTS,
  REPO_ROOT,
  SEED_CREDENTIALS_PATH,
  STATE_DIR,
  renderEnv,
  writePrivate,
} from "./lib/local-state.mjs";

// Kept OUT of mingla-business/: Metro bundles a `.env.*` file found in the
// project root as a module and the web bundle then fails to build.
export const BUSINESS_ENV_PATH = resolve(STATE_DIR, "business-web.env");
export const CORE_STATUS_PATH = resolve(STATE_DIR, "core.status.env");
// Shape-only placeholder: app.config.js needs a pk_test_ value under
// MINGLA_STRIPE_MODE=test. Payments are not part of the local Sites stack.
export const LOCAL_STRIPE_PLACEHOLDER = "pk_test_localsitesstack_not_a_real_key";

export function readCoreStatus(path = CORE_STATUS_PATH) {
  if (!existsSync(path)) {
    throw new Error("CORE_STATUS_MISSING: start the stack with scripts/sites/local/start-local-sites.sh first");
  }
  const values = parseEnvFile(readFileSync(path, "utf8"));
  const apiUrl = values.API_URL;
  const anonKey = values.ANON_KEY || values.PUBLISHABLE_KEY;
  const serviceRoleKey = values.SERVICE_ROLE_KEY || values.SECRET_KEY;
  if (!apiUrl || !anonKey || !serviceRoleKey) throw new Error("CORE_STATUS_INCOMPLETE");
  assertLoopbackUrl(apiUrl, "core.api");
  return { apiUrl: apiUrl.replace(/\/$/, ""), anonKey, serviceRoleKey };
}

export function parsePort(raw) {
  const port = Number(raw);
  if (!Number.isInteger(port) || port < 1024 || port > 65535) throw new Error("BAD_PORT");
  return port;
}

export function businessEnvEntries({ apiUrl, anonKey }, port) {
  assertLoopbackUrl(apiUrl, "core.api");
  return [
    ["EXPO_PUBLIC_SUPABASE_URL", apiUrl],
    ["EXPO_PUBLIC_SUPABASE_ANON_KEY", anonKey],
    ["EXPO_PUBLIC_FF_SITES_ENABLED", "true"],
    ["EXPO_PUBLIC_SITES_LOCAL_STUDIO_ORIGIN", `http://localhost:${PORTS.studio}`],
    ["EXPO_PUBLIC_MINGLA_BUSINESS_WEB_URL", `http://localhost:${port}`],
    ["MINGLA_STRIPE_MODE", "test"],
    ["EXPO_PUBLIC_STRIPE_PUBLISHABLE_KEY", LOCAL_STRIPE_PLACEHOLDER],
    // Keep analytics and crash reporting off: a local session must not reach
    // the hosted PostHog / Sentry projects.
    ["EXPO_PUBLIC_POSTHOG_KEY", ""],
    ["EXPO_PUBLIC_SENTRY_DSN", ""],
  ];
}

export function resolveSeedEmail(who, credentialsPath = SEED_CREDENTIALS_PATH) {
  if (!who) throw new Error("WHO_REQUIRED: a seeded role (brand_owner, marketing_manager, ...) or email");
  if (who.includes("@")) {
    if (!who.endsWith("@local.invalid")) throw new Error("NOT_A_LOCAL_SEED_USER");
    return who;
  }
  if (!existsSync(credentialsPath)) throw new Error("SEED_CREDENTIALS_MISSING");
  const users = JSON.parse(readFileSync(credentialsPath, "utf8")).users ?? {};
  const email = users[who]?.email;
  if (!email) throw new Error(`UNKNOWN_ROLE:${who} (known: ${Object.keys(users).join(", ")})`);
  return email;
}

async function signInCode(email, core) {
  assertLoopbackUrl(core.apiUrl, "core.api");
  const response = await fetch(`${core.apiUrl}/auth/v1/admin/generate_link`, {
    method: "POST",
    headers: {
      apikey: core.serviceRoleKey,
      authorization: `Bearer ${core.serviceRoleKey}`,
      "content-type": "application/json",
    },
    body: JSON.stringify({ type: "magiclink", email }),
  });
  const body = await response.json().catch(() => ({}));
  if (!response.ok || typeof body.email_otp !== "string") {
    throw new Error(`CODE_FAILED:${response.status}:${body.msg ?? body.error ?? "no code returned"}`);
  }
  return body.email_otp;
}

async function main(argv) {
  const [command, ...rest] = argv;
  if (command === "env") {
    const index = rest.indexOf("--port");
    const port = parsePort(index >= 0 ? rest[index + 1] : "8190");
    const core = readCoreStatus();
    writePrivate(
      BUSINESS_ENV_PATH,
      renderEnv(
        "# #2829 generated by scripts/sites/local/business-web.mjs — local Sites stack only. Gitignored; do not commit.",
        businessEnvEntries(core, port),
      ),
    );
    process.stdout.write(`wrote ${BUSINESS_ENV_PATH.replace(`${REPO_ROOT}/`, "")} (Core ${core.apiUrl}, Studio http://localhost:${PORTS.studio})\n`);
    return;
  }
  if (command === "code") {
    const email = resolveSeedEmail(rest[0]);
    const code = await signInCode(email, readCoreStatus());
    process.stdout.write(`${email}: ${code}\n`);
    return;
  }
  throw new Error("USAGE: business-web.mjs env --port <port> | code <role|email>");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch((error) => {
    process.stderr.write(`FAIL business-web: ${error.message}\n`);
    process.exit(1);
  });
}
