#!/usr/bin/env node
// #2829 W0 — generate local key material and write the three gitignored env
// files for the local Sites stack:
//   mingla-sites/.env.local          (public runtime, local mode)
//   mingla-site-cms/.env.local       (Studio, local mode)
//   supabase/functions/.env.local    (MINGLA_SITES_SECURITY_JSON for Core functions)
// plus scripts/sites/local/.state/cms-ops.env (bootstrap/migration-only values).
//
// Key material is generated once into .state/local-secrets.json and reused on
// every run (pass --rotate to regenerate). Values are never printed.
//
// Usage: generate-local-keys.mjs --core-status <file> --cms-status <file> [--rotate]
//   where each status file is `supabase status -o env` output for that stack.

import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";

import {
  CMS_OPS_ENV_PATH,
  LOCAL_HOST_SUFFIX,
  LOCAL_SITES_PROJECT_REF,
  PORTS,
  REPO_ROOT,
  SECRETS_PATH,
  assertLoopbackUrl,
  newSecrets,
  parseEnvFile,
  readSecrets,
  renderEnv,
  writePrivate,
  writeSecrets,
} from "./lib/local-state.mjs";

function arg(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

function status(path, label) {
  if (!path || !existsSync(path)) throw new Error(`STATUS_FILE_MISSING:${label}`);
  const values = parseEnvFile(readFileSync(path, "utf8"));
  const pick = (...names) => names.map((name) => values[name]).find(Boolean);
  const result = {
    apiUrl: pick("API_URL"),
    dbUrl: pick("DB_URL"),
    anonKey: pick("ANON_KEY", "PUBLISHABLE_KEY"),
    serviceRoleKey: pick("SERVICE_ROLE_KEY", "SECRET_KEY"),
    s3AccessKeyId: pick("S3_PROTOCOL_ACCESS_KEY_ID"),
    s3SecretAccessKey: pick("S3_PROTOCOL_ACCESS_KEY_SECRET"),
  };
  for (const [name, value] of Object.entries(result)) {
    if (!value && !(label === "core" && name.startsWith("s3"))) {
      throw new Error(`STATUS_VALUE_MISSING:${label}:${name}`);
    }
  }
  assertLoopbackUrl(result.apiUrl, `${label}.api`);
  assertLoopbackUrl(result.dbUrl, `${label}.db`);
  return result;
}

const LOCAL_ONLY_HEADER = (app) => `
# GENERATED by scripts/sites/local/generate-local-keys.mjs for the LOCAL
# Sites stack (#2829). Gitignored. Never copy these values into Vercel or any
# hosted environment: ${app} refuses local mode on Vercel and refuses
# non-loopback backends in local mode.`;

function main() {
  const rotate = process.argv.includes("--rotate");
  const core = status(arg("--core-status"), "core");
  const cms = status(arg("--cms-status"), "cms");
  if (Number(new URL(cms.apiUrl).port) !== PORTS.cmsApi) {
    throw new Error("CMS_STACK_PORT_UNEXPECTED");
  }

  const fresh = rotate || !existsSync(SECRETS_PATH);
  const secrets = fresh ? newSecrets() : readSecrets();
  writeSecrets(secrets);
  const { keys, cms_roles: roles, storage_reader: reader, fixtures } = secrets;

  const coreOrigin = new URL(core.apiUrl).origin;
  const cmsApiOrigin = new URL(cms.apiUrl).origin;
  const studioOrigin = `http://localhost:${PORTS.studio}`;
  const runtimeOrigin = `http://localhost:${PORTS.runtime}`;
  const cmsDb = new URL(cms.dbUrl);
  const cmsDbHostPort = `${cmsDb.hostname}:${cmsDb.port}`;
  const pg = (user, pw) => ["postgresql://", user, ":", encodeURIComponent(pw), "@", cmsDbHostPort, "/postgres"].join("");

  writePrivate(
    resolve(REPO_ROOT, "mingla-sites/.env.local"),
    renderEnv(LOCAL_ONLY_HEADER("mingla-sites"), [
      ["SITES_LOCAL_MODE", "1"],
      ["SITES_CORE_BASE_URL", coreOrigin],
      ["SITES_CORE_ANON_KEY", core.anonKey],
      ["SITES_CMS_PROJECT_REF", LOCAL_SITES_PROJECT_REF],
      ["SITES_STORAGE_SUPABASE_URL", cmsApiOrigin],
      ["SITES_STORAGE_SUPABASE_ANON_KEY", cms.anonKey],
      ["SITES_STORAGE_READER_EMAIL", reader.email],
      ["SITES_STORAGE_READER_PASSWORD", reader.password],
      ["SITES_PUBLICATION_ARTIFACT_BUCKET", "sites-publication-artifacts"],
      ["SITES_MEDIA_APPROVED_BUCKET", "sites-media-approved"],
      ["SITES_ALLOWED_HOST_SUFFIX", LOCAL_HOST_SUFFIX],
      ["MINGLA_RUNTIME_TO_CORE_CURRENT_KID", keys.runtime_to_core.kid],
      ["MINGLA_RUNTIME_TO_CORE_CURRENT_KEY_B64", keys.runtime_to_core.key_b64],
      ["SITES_CANDIDATE_PROBE_SECRET", keys.candidate_probe_secret_b64],
      ["SITES_RUNTIME_MEDIA_KEY_B64", keys.runtime_media_key_b64],
    ]),
  );

  writePrivate(
    resolve(REPO_ROOT, "mingla-site-cms/.env.local"),
    renderEnv(LOCAL_ONLY_HEADER("mingla-site-cms"), [
      ["SITES_LOCAL_MODE", "1"],
      ["DATABASE_URL", pg("sites_cms_app", roles.app_password)],
      ["SITES_DATABASE_CONNECTION_MODE", "runtime"],
      ["PAYLOAD_SECRET", keys.payload_secret_b64],
      ["SITES_CORE_BASE_URL", coreOrigin],
      ["SITES_CMS_ORIGIN", studioOrigin],
      ["SITES_PUBLIC_RUNTIME_ORIGIN", runtimeOrigin],
      ["SITES_LOCAL_BUSINESS_ORIGIN", `http://localhost:${PORTS.businessWeb}`],
      ["SUPABASE_S3_ENDPOINT", `${cmsApiOrigin}/storage/v1/s3`],
      ["SUPABASE_S3_REGION", "local"],
      ["SUPABASE_S3_ACCESS_KEY_ID", cms.s3AccessKeyId],
      ["SUPABASE_S3_SECRET_ACCESS_KEY", cms.s3SecretAccessKey],
      ["SITES_MEDIA_QUARANTINE_BUCKET", "sites-media-quarantine"],
      ["SITES_MEDIA_APPROVED_BUCKET", "sites-media-approved"],
      ["SITES_PUBLICATION_ARTIFACT_BUCKET", "sites-publication-artifacts"],
      ["SITES_MEDIA_RECOVERY_BUCKET", "sites-media-recovery"],
      ["SITES_PREVIEW_SIGNING_SECRET", keys.preview_signing_secret_b64],
      ["MINGLA_CMS_TO_CORE_CURRENT_KID", keys.cms_to_core.kid],
      ["MINGLA_CMS_TO_CORE_CURRENT_KEY_B64", keys.cms_to_core.key_b64],
      ["MINGLA_CORE_TO_CMS_CURRENT_KID", keys.core_to_cms.kid],
      ["MINGLA_CORE_TO_CMS_CURRENT_KEY_B64", keys.core_to_cms.key_b64],
      ["SITES_CANDIDATE_PROBE_SECRET", keys.candidate_probe_secret_b64],
    ]),
  );

  // Bootstrap / migration-only values: never loaded by the Studio app itself.
  writePrivate(
    CMS_OPS_ENV_PATH,
    renderEnv("# GENERATED (#2829 local Sites stack): CMS bootstrap + migration only.", [
      ["SITES_CMS_PROJECT_REF", LOCAL_SITES_PROJECT_REF],
      ["SITES_CMS_ADMIN_DATABASE_URL", cms.dbUrl],
      ["SITES_CMS_MIGRATOR_DATABASE_URL", pg("sites_cms_migrator", roles.migrator_password)],
      ["SITES_CMS_MIGRATOR_PASSWORD", roles.migrator_password],
      ["SITES_CMS_APP_PASSWORD", roles.app_password],
      // Until the reader exists the policy is bound to a placeholder subject;
      // start-local-sites.sh re-runs the bootstrap once the reader is created.
      ["SITES_RUNTIME_READER_SUBJECT", reader.user_id || "00000000-0000-4000-8000-000000000000"],
      // The site the (single-tenant) backup tooling scopes to and signs
      // recovery alerts for; the runtime and the reader policy serve all sites.
      ["SITES_PILOT_SITE_ID", fixtures.gogi_site_id],
    ]),
  );

  const securityJson = JSON.stringify({
    schema_version: 1,
    attribution_pepper_b64: keys.attribution_pepper_b64,
    cms_to_core_current_kid: keys.cms_to_core.kid,
    cms_to_core_current_key_b64: keys.cms_to_core.key_b64,
    cms_to_core_previous_kid: null,
    cms_to_core_previous_key_b64: null,
    core_to_cms_current_kid: keys.core_to_cms.kid,
    core_to_cms_current_key_b64: keys.core_to_cms.key_b64,
    core_to_cms_previous_kid: null,
    core_to_cms_previous_key_b64: null,
    runtime_to_core_current_kid: keys.runtime_to_core.kid,
    runtime_to_core_current_key_b64: keys.runtime_to_core.key_b64,
    runtime_to_core_previous_kid: null,
    runtime_to_core_previous_key_b64: null,
  });
  writePrivate(
    resolve(REPO_ROOT, "supabase/functions/.env.local"),
    renderEnv(LOCAL_ONLY_HEADER("Core Sites functions"), [
      ["MINGLA_SITES_SECURITY_JSON", `'${securityJson}'`],
      // #2829 W8 — brand-site-domains asks the local runtime (on the host)
      // for /.well-known/mingla-site through the Docker host gateway. Read
      // only when the Sites service row is 'local' (local adapters only).
      ["SITES_LOCAL_PROBE_ORIGIN", `http://host.docker.internal:${PORTS.runtime}`],
    ]),
  );

  process.stdout.write(
    `SITES_LOCAL_KEYS_OK files=4 key_material=${fresh ? "generated" : "reused"}\n`,
  );
}

try {
  main();
} catch (error) {
  process.stderr.write(`FAIL generate-local-keys: ${error instanceof Error ? error.message : "unknown"}\n`);
  process.exit(1);
}
