#!/usr/bin/env node
/*
 * #2829 — copy packages/site-contracts/src into every consumer.
 *
 * The Vercel projects build from their own root directories and may not see
 * files outside them, so each consumer carries a byte-for-byte copy of the
 * contracts with a header naming the source file and its SHA-256. Each
 * consumer has a drift test; `--check` is the same comparison for CI and
 * exits 1 naming every stale or missing copy.
 *
 *   node scripts/sites/sync-site-contracts.mjs          # write the copies
 *   node scripts/sites/sync-site-contracts.mjs --check  # verify, write nothing
 */
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const SOURCE_DIR = path.join(REPO, "packages/site-contracts/src");
export const TARGET_DIRS = [
  "mingla-sites/src/contracts/generated",
  "mingla-site-cms/src/contracts/generated",
  "supabase/functions/_shared/siteContracts",
].map((dir) => path.join(REPO, dir));

export function headerFor(file, source) {
  const digest = createHash("sha256").update(source).digest("hex");
  return `// GENERATED by scripts/sites/sync-site-contracts.mjs from packages/site-contracts/src/${file} sha256:${digest} — do not edit; edit the package and re-run the script.\n`;
}

export function expectedCopies() {
  const files = fs.readdirSync(SOURCE_DIR)
    .filter((file) => file.endsWith(".ts") && !file.includes(".test."))
    .sort();
  return files.map((file) => {
    const source = fs.readFileSync(path.join(SOURCE_DIR, file), "utf8");
    return { file, content: headerFor(file, source) + source };
  });
}

export function driftReport() {
  const problems = [];
  const copies = expectedCopies();
  const names = new Set(copies.map((copy) => copy.file));
  for (const dir of TARGET_DIRS) {
    for (const copy of copies) {
      const target = path.join(dir, copy.file);
      if (!fs.existsSync(target)) problems.push(`missing ${path.relative(REPO, target)}`);
      else if (fs.readFileSync(target, "utf8") !== copy.content) {
        problems.push(`stale ${path.relative(REPO, target)}`);
      }
    }
    if (fs.existsSync(dir)) {
      for (const file of fs.readdirSync(dir)) {
        if (file.endsWith(".ts") && !names.has(file)) {
          problems.push(`orphan ${path.relative(REPO, path.join(dir, file))}`);
        }
      }
    }
  }
  return problems;
}

function main() {
  if (process.argv.includes("--check")) {
    const problems = driftReport();
    if (problems.length) {
      console.error(`SITE_CONTRACTS_DRIFT\n${problems.join("\n")}\nRun: node scripts/sites/sync-site-contracts.mjs`);
      process.exit(1);
    }
    console.log("SITE_CONTRACTS_IN_SYNC");
    return;
  }
  const copies = expectedCopies();
  const names = new Set(copies.map((copy) => copy.file));
  for (const dir of TARGET_DIRS) {
    fs.mkdirSync(dir, { recursive: true });
    for (const file of fs.readdirSync(dir)) {
      if (file.endsWith(".ts") && !names.has(file)) fs.rmSync(path.join(dir, file));
    }
    for (const copy of copies) fs.writeFileSync(path.join(dir, copy.file), copy.content);
  }
  console.log(`SITE_CONTRACTS_SYNCED files=${copies.length} targets=${TARGET_DIRS.length}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
