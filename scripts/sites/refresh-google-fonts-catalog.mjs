#!/usr/bin/env node
/*
 * #2829 AD-3 — regenerate the Google Fonts catalogue Sites owners choose from.
 *
 * Reads Google's PUBLIC font metadata (no key, no account) and writes
 * packages/site-contracts/src/googleFontsCatalog.ts: one row per open-source
 * family with its category, the weights it offers upright and italic, and its
 * subsets. The file is committed and reviewed like any data file; nothing at
 * runtime calls Google for the catalogue, and no visitor's browser ever does.
 *
 *   node scripts/sites/refresh-google-fonts-catalog.mjs            # fetch + write
 *   node scripts/sites/refresh-google-fonts-catalog.mjs --from f   # write from a saved response
 *
 * Then run scripts/sites/sync-site-contracts.mjs to copy it into consumers.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const METADATA_URL = "https://fonts.google.com/metadata/fonts";
export const TARGET = path.join(REPO, "packages/site-contracts/src/googleFontsCatalog.ts");

const CATEGORY = {
  "Sans Serif": "sans-serif",
  Serif: "serif",
  Display: "display",
  Handwriting: "handwriting",
  Monospace: "monospace",
};
const FAMILY = /^[A-Za-z0-9](?:[A-Za-z0-9 -]{0,62}[A-Za-z0-9])?$/;

/** Google prefixes the JSON with an anti-XSSI line; take from the first brace. */
export function parseMetadata(raw) {
  const start = raw.indexOf("{");
  if (start < 0) throw new Error("GOOGLE_FONTS_METADATA_UNREADABLE");
  const parsed = JSON.parse(raw.slice(start));
  if (!Array.isArray(parsed.familyMetadataList)) throw new Error("GOOGLE_FONTS_METADATA_UNREADABLE");
  return parsed.familyMetadataList;
}

/** Rows: [family, category, upright weights, italic weights, subsets]. */
export function catalogRows(families) {
  const rows = [];
  for (const family of families) {
    if (family.isOpenSource !== true) continue;
    if (typeof family.family !== "string" || !FAMILY.test(family.family)) continue;
    const category = CATEGORY[family.category];
    if (!category) continue;
    const upright = [];
    const italic = [];
    for (const key of Object.keys(family.fonts ?? {})) {
      const match = /^([1-9]00)(i?)$/.exec(key);
      if (!match) continue;
      (match[2] ? italic : upright).push(Number(match[1]));
    }
    if (upright.length === 0) continue;
    const subsets = (family.subsets ?? []).filter((subset) => subset !== "menu" && /^[a-z0-9-]+$/.test(subset)).sort();
    rows.push([family.family, category, upright.sort((a, b) => a - b), italic.sort((a, b) => a - b), subsets]);
  }
  rows.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  return rows;
}

export function renderModule(rows, fetchedOn) {
  const body = rows.map((row) => `  ${JSON.stringify(row)},`).join("\n");
  return `/**
 * #2829 AD-3 — GENERATED by scripts/sites/refresh-google-fonts-catalog.mjs
 * from Google's public font metadata (${METADATA_URL}), ${fetchedOn}.
 * Every family is open source (SIL OFL, Apache 2.0 or Ubuntu Font Licence, as
 * published by Google Fonts). Do not edit by hand; re-run the script.
 *
 * Row: [family, category, upright weights, italic weights, subsets].
 */
export type GoogleFontRow = readonly [
  family: string,
  category: "sans-serif" | "serif" | "display" | "handwriting" | "monospace",
  weights: readonly number[],
  italicWeights: readonly number[],
  subsets: readonly string[],
];

export const GOOGLE_FONTS_CATALOG_FETCHED_ON = ${JSON.stringify(fetchedOn)};

export const GOOGLE_FONTS_CATALOG: readonly GoogleFontRow[] = [
${body}
];
`;
}

async function main() {
  const fromIndex = process.argv.indexOf("--from");
  const raw = fromIndex > 0
    ? fs.readFileSync(process.argv[fromIndex + 1], "utf8")
    : await (async () => {
      const response = await fetch(METADATA_URL, { redirect: "error" });
      if (!response.ok) throw new Error(`GOOGLE_FONTS_METADATA_HTTP_${response.status}`);
      return response.text();
    })();
  const rows = catalogRows(parseMetadata(raw));
  if (rows.length < 1000) throw new Error(`GOOGLE_FONTS_CATALOG_TOO_SMALL:${rows.length}`);
  const fetchedOn = new Date().toISOString().slice(0, 10);
  fs.writeFileSync(TARGET, renderModule(rows, fetchedOn));
  console.log(`GOOGLE_FONTS_CATALOG_WRITTEN families=${rows.length} target=${path.relative(REPO, TARGET)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  });
}
